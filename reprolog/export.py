"""Turn a capture into a curl command or a pytest regression test."""
from __future__ import annotations

import json
import os
import shlex

from .config import REDACTED
from .redact import decode_body
from .replay import SKIP_REPLAY_HEADERS


def original_url(record: dict) -> str | None:
    """The URL the client actually called, as far as the proxy headers tell (None if unknown)."""
    req = record["request"]
    headers = {str(k).lower(): v for k, v in req.get("headers") or []}
    host = (headers.get("x-forwarded-host") or headers.get("host") or "").split(",")[0].strip()
    if not host:
        return None
    scheme = (headers.get("x-forwarded-proto") or req.get("scheme") or "http").split(",")[0].strip()
    # raw_path is what the server received, before middleware such as path stripping changed it.
    path = req.get("raw_path") or (req.get("root_path") or "") + req["path"]
    url = f"{scheme}://{host}{path}"
    if req.get("query_string"):
        url += "?" + req["query_string"]
    return url


def to_curl(record: dict, base_url: str | None = "http://localhost:8000") -> str:
    """curl for the request. base_url=None targets the original (live) URL."""
    req = record["request"]
    url = original_url(record) if base_url is None else None
    if url is None:
        url = (base_url or "http://localhost:8000").rstrip("/") + (req.get("root_path") or "") + req["path"]
        if req.get("query_string"):
            url += "?" + req["query_string"]
    parts = [f"curl -X {req['method']} {shlex.quote(url)}"]
    for name, value in req["headers"]:
        if name.lower() in SKIP_REPLAY_HEADERS or name.lower().startswith("x-forwarded-"):
            continue
        if value == REDACTED:
            value = "<redacted: paste a fresh value>"
        parts.append(f"-H {shlex.quote(f'{name}: {value}')}")
    body = req.get("body") or {}
    if body.get("encoding") == "text" and body.get("data"):
        parts.append(f"--data-raw {shlex.quote(body['data'])}")
    elif body.get("encoding") == "base64":
        parts.append("--data-binary @body.bin  # binary body: see `reprolog show --json`")
    return " \\\n  ".join(parts)


TEST_TEMPLATE = '''"""Regression test generated by reprolog from capture {cid}.

Original failure: {method} {path} -> {status} {error}
Outbound HTTP/LLM calls are served from the recording. Database and Redis are live.
Passes once the bug is fixed (no unhandled error and status below 500).
"""
import asyncio
import json
import pathlib

from reprolog.replay import load_app, replay_record

RECORD = json.loads(pathlib.Path(__file__).with_name("{fixture}").read_text())
HEADER_OVERRIDES = []  # e.g. ["Authorization: Bearer <fresh token>"]


def test_{fn}():
    app = load_app("{app_path}")
    result = asyncio.run(replay_record(RECORD, app, header_overrides=HEADER_OVERRIDES))
    replayed = result["replayed"]
    error = replayed.get("error")
    assert error is None, f"{{error['type']}}: {{error['message']}}"
    assert (replayed["response"]["status"] or 0) < 500
'''


def to_pytest(record: dict, app_path: str, out_dir: str = "tests") -> tuple[str, str]:
    os.makedirs(out_dir, exist_ok=True)
    cid = record["id"]
    fixture = f"reprolog_{cid}.json"
    test_file = os.path.join(out_dir, f"test_reprolog_{cid}.py")
    with open(os.path.join(out_dir, fixture), "w") as fh:
        json.dump(record, fh, indent=2, ensure_ascii=False, default=str)
    req, err = record["request"], record.get("error") or {}
    with open(test_file, "w") as fh:
        fh.write(TEST_TEMPLATE.format(
            cid=cid, method=req["method"], path=req["path"], status=record["response"].get("status"),
            error=f"({err.get('type')}: {err.get('message', '')[:80]})" if err else "",
            fixture=fixture, fn=f"replay_{cid}", app_path=app_path,
        ))
    return test_file, os.path.join(out_dir, fixture)


def body_bytes(record: dict) -> bytes:
    return decode_body(record["request"].get("body"))
